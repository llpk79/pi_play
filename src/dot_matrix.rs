use rppal::gpio;
use rppal::gpio::Gpio;
use std::io;
use std::sync::mpsc;
use std::thread;
use std::time::Duration;

const RCLK: u8 = 17;
const SRCLK: u8 = 27;
const SDI: u8 = 22;

const FRAME_REPEATS: usize = 15;
const DISPLAY_WIDTH: usize = 8;
const SCROLL_SPEED: u64 = 500; // Bigger == slower
const TAB: [u8; DISPLAY_WIDTH] = [0xfe, 0xfd, 0xfb, 0xf7, 0xef, 0xdf, 0xbf, 0x7f];
const PAD: [u8; DISPLAY_WIDTH] = [0; DISPLAY_WIDTH];

fn get_user_input() -> String {
    let mut message = String::new();
    println!("Enter your message");
    io::stdin().read_line(&mut message).expect("chars");
    message = message.trim().to_string();
    message
}

#[derive(Debug)]
pub struct DotMatrix {
    rclk: gpio::OutputPin,
    srclk: gpio::OutputPin,
    sdi: gpio::OutputPin,
}

impl DotMatrix {
    pub fn new() -> DotMatrix {
        let gpio = Gpio::new().expect("Board exists");
        let mut rclk = gpio.get(RCLK).expect("Pin active").into_output();
        rclk.set_low();
        let mut srclk = gpio.get(SRCLK).expect("Pin active").into_output();
        srclk.set_low();
        let mut sdi = gpio.get(SDI).expect("Pin active").into_output();
        sdi.set_low();

        Self { rclk, srclk, sdi }
    }

    fn input(&mut self, data: u8) {
        for bit in (0..8).rev() {
            if data & (1 << bit) != 0 {
                self.sdi.set_high();
            } else {
                self.sdi.set_low();
            }

            self.srclk.set_high();
            self.srclk.set_low();
        }
    }

    fn output(&mut self) {
        self.rclk.set_high();
        self.rclk.set_low();
    }

    fn display_data(&mut self, data: &[u8]) {
        for window in data.windows(DISPLAY_WIDTH) {
            for _ in 0..FRAME_REPEATS {
                for (&column, &select) in window.iter().zip(TAB.iter()) {
                    self.input(column);
                    self.input(select);
                    self.output();

                    thread::sleep(Duration::from_micros(SCROLL_SPEED));
                }
            }
        }
    }
    /// Asks for user input, then loops message display until user enters new message
    pub fn display_user_message(mut self, characters: Characters) {
        let (tx, rx) = mpsc::channel();
        let get_message = thread::Builder::new()
            .name("tx".to_string())
            .spawn(move || loop {
                let message = get_user_input();
                tx.send(message).unwrap();
            });
        let display_message = thread::Builder::new()
            .name("rx".to_string())
            .spawn(move || {
                let mut message = String::new();
                loop {
                    if let Ok(new_message) = rx.try_recv() {
                        let encoded_message = characters.encode_message(&new_message);
                        self.display_data(&encoded_message);
                        message = new_message;
                    } else {
                        let encoded_message = characters.encode_message(&message);
                        self.display_data(&encoded_message);
                    };
                }
            });
        get_message.expect("thread exists").join().unwrap();
        display_message.expect("thread exists").join().unwrap();
    }
}

